local F = require 'mpv_luatest.framework'
local S = require 'support'
local asyncio = require 'elxlibs.asyncio'
local std = require 'elxlibs.std'
local queues = require 'elxlibs.asyncio.queues'
local await = asyncio.await

F.section('Queue / LifoQueue')

F.test('nowait boundaries, FIFO/LIFO order and unfinished task accounting', function()
    S.run(function()
        local q = queues.Queue(2)
        F.eq(q:empty(), true, 'new queue empty')
        F.eq(q:full(), false, 'new queue not full')
        F.raises(function() q:get_nowait() end, 'QueueEmpty', 'empty get rejected')
        q:put_nowait('one')
        q:put_nowait('two')
        F.eq(assert(q.__len)(S.invalid(q)), 2, 'queue size')
        F.eq(q:full(), true, 'bound reached')
        F.raises(function() q:put_nowait('three') end, 'QueueFull', 'full put rejected')
        F.eq(q:get_nowait(), 'one', 'FIFO first')
        F.eq(q:get_nowait(), 'two', 'FIFO second')
        local joined = asyncio.create_task(q:join())
        await(asyncio.sleep(0))
        F.eq(joined:done(), false, 'get alone does not mark tasks finished')
        q:task_done()
        await(asyncio.sleep(0))
        F.eq(joined:done(), false, 'join waits for all tasks')
        q:task_done()
        await(joined)
        await(q:join())
        F.raises(function() q:task_done() end, 'ValueError', 'excess task_done rejected')
        local lifo = queues.LifoQueue()
        lifo:put_nowait('first')
        lifo:put_nowait('last')
        F.eq(lifo:get_nowait(), 'last', 'LIFO last first')
        F.eq(lifo:get_nowait(), 'first', 'LIFO first last')
        F.eq(lifo:full(), false, 'default queue unbounded')
        lifo:task_done()
        lifo:task_done()
    end)
end)

F.test('cancelled getters leave later consumers able to receive items', function()
    S.run(function()
        local q = queues.Queue()
        local a = asyncio.create_task(q:get())
        local b = asyncio.create_task(q:get())
        await(asyncio.sleep(0))
        a:cancel()
        asyncio.try_await(a)
        q:put_nowait('delivered')
        F.eq(await(b), 'delivered', 'surviving getter receives item')
        F.eq(#q._getters, 0, 'cancelled/completed getters removed')
        q:task_done()
        await(q:join())
    end)
end)

F.test('cancelled putters leave capacity for later producers', function()
    S.run(function()
        local q = queues.Queue(1)
        q:put_nowait('initial')
        local a = asyncio.create_task(q:put('cancelled'))
        local b = asyncio.create_task(q:put('survivor'))
        await(asyncio.sleep(0))
        a:cancel()
        asyncio.try_await(a)
        F.eq(q:get_nowait(), 'initial', 'original item kept')
        q:task_done()
        await(b)
        F.eq(q:get_nowait(), 'survivor', 'surviving producer enqueued')
        F.eq(#q._putters, 0, 'cancelled/completed putters removed')
        q:task_done()
        await(q:join())
    end)
end)

F.test('cancelled join does not alter unfinished work', function()
    S.run(function()
        local q = queues.Queue()
        q:put_nowait('work')
        local join = asyncio.create_task(q:join())
        await(asyncio.sleep(0))
        join:cancel()
        F.eq(asyncio.try_await(join), false, 'join cancellation reported')
        F.eq(q:get_nowait(), 'work', 'work preserved')
        q:task_done()
        await(q:join())
        F.eq(q._unfinished_tasks, 0, 'subsequent join completes')
    end)
end)
