local F = require 'mpv_luatest.framework'
local S = require 'support'
local asyncio = require 'elxlibs.asyncio'
local std = require 'elxlibs.std'
local events = asyncio.events

F.section('event loops / handles')

F.test('loop lookup and run lifecycle restore state on success and error', function()
    local a, b = events.get_event_loop(), events.get_event_loop()
    F.ok(a ~= b, 'outside run lookup creates a new loop')
    a:close()
    b:close()
    F.eq(pcall(events.get_running_loop), false, 'no running loop outside run')
    local loop = S.real_loop(asyncio)
    local result = table.pack(asyncio.run(function()
        F.eq(loop:is_running(), true, 'running during body')
        F.eq(events.get_event_loop(), loop, 'event loop lookup during run')
        F.eq(events.get_running_loop(), loop, 'running lookup')
        F.eq(pcall(loop.close, loop), false, 'cannot close a running loop')
        F.eq(pcall(loop.run_forever, loop), false, 'cannot reenter running loop')
        local other = asyncio.loops.new_event_loop()
        F.eq(pcall(other.run_forever, other), false, 'cannot nest a different loop')
        other:close()
        return 'value', nil
    end, loop))
    F.eq(result.n, 2, 'run preserves result count')
    F.eq(loop:is_running(), false, 'running cleared after return')
    F.eq(pcall(events.get_running_loop), false, 'global running loop cleared')
    local boom = std.RuntimeError('run-boom')
    local ok, err = pcall(asyncio.run, function() error(boom) end, loop)
    F.eq(ok, false, 'body error propagated')
    F.eq(err, boom, 'run preserves exception identity')
    F.eq(loop:is_running(), false, 'running cleared after failure')
    F.eq(pcall(events.get_running_loop), false, 'global loop cleared after failure')
    loop:close()
end)

F.test('call_soon/later/at preserve ordering and expose cancellation handles', function()
    local loop = S.real_loop(asyncio)
    local order = {}
    local cancelled = loop:call_soon(function() order[#order + 1] = 'cancelled' end)
    cancelled:cancel()
    cancelled:cancel()
    local when = loop:time()
    loop:call_at(when, function(value) order[#order + 1] = value end, {'first'})
    loop:call_at(when, function() order[#order + 1] = 'second' end)
    local timer = loop:call_later(0, function() order[#order + 1] = 'timer-cancelled' end)
    F.ok(std.isinstance(timer, events.TimerHandle), 'timer handle type')
    F.ok(std.isinstance(timer, events.Handle), 'timer inherits handle')
    timer:cancel()
    loop:call_soon(function()
        order[#order + 1] = 'soon'
        loop:call_soon(function()
            order[#order + 1] = 'next-cycle'
            loop:stop()
        end)
    end)
    loop:call_soon(function(...)
        F.eq(select('#', ...), 3, 'packed callback arguments keep trailing nil')
    end, table.pack('argument', nil, nil))
    loop:run_forever()
    F.eq(table.concat(order, ','), 'soon,first,second,next-cycle', 'FIFO and next-cycle order')
    F.eq(cancelled.func, nil, 'cancel releases callback')
    F.eq(cancelled.args, nil, 'cancel releases arguments')
    F.eq(pcall(loop.call_at, loop, S.invalid(nil), function() end), false, 'nil deadline rejected')
    F.eq(pcall(loop.call_soon, loop, S.invalid(42)), false, 'invalid immediate callback rejected')
    F.eq(pcall(loop.call_later, loop, 0, S.invalid(42)), false, 'invalid delayed callback rejected')
    loop:close()
end)

F.test('exception handlers receive context and default logs error', function()
    local loop = S.real_loop(asyncio)
    ---@type {context?: asyncio._exc_handler_context}
    local received = {}
    local handler = function(context) received.context = context end
    loop:set_exception_handler(handler)
    F.eq(loop:get_exception_handler(), handler, 'handler getter')
    local boom = std.RuntimeError('callback-boom')
    local handle = loop:call_soon(function() error(boom) end)
    loop:call_soon(function() loop:stop() end)
    loop:run_forever()
    local context = assert(received.context)
    F.eq(context.handle, handle, 'failed callback handle')
    F.contains(context.exception, 'callback-boom', 'callback error context')
    local mp = S.invalid(require 'mp')
    local before = #mp.messages
    local default = asyncio.loops.new_event_loop()
    F.eq(default:get_exception_handler(), nil, 'default has no custom handler')
    default:call_exception_handler({exception = 'default-boom'})
    F.eq(#mp.messages, before + 1, 'default handler logs once')
    F.contains(mp.messages[#mp.messages], 'default-boom', 'error text logged')
    F.eq(pcall(loop.set_exception_handler, loop, S.invalid(42)), false, 'invalid handler rejected')
    loop:close()
    default:close()
end)

F.test('closed and foreign-loop operations reject invalid lifecycle', function()
    local a, b = asyncio.loops.new_event_loop(), asyncio.loops.new_event_loop()
    local future = b:create_future()
    local ok, err = pcall(a.run_until_complete, a, future)
    F.eq(ok, false, 'foreign future rejected')
    F.ok(std.isinstance(err, std.ValueError), 'typed foreign future error')
    a:call_soon(function() end)
    a:call_later(10, function() end)
    a:close()
    a:close()
    F.eq(a:closed(), true, 'idempotently closed')
    F.eq(#a._ready, 0, 'ready queue cleared')
    F.eq(#a._scheduled, 0, 'timer queue cleared')
    F.eq(pcall(a.run_forever, a), false, 'closed loop cannot run')
    F.eq(pcall(a.create_task, a, function() end), false, 'closed loop cannot create tasks')
    F.eq(pcall(a.call_soon, a, function() end), false, 'closed loop cannot schedule')
    F.eq(pcall(a.call_later, a, 0, function() end), false, 'closed loop cannot create timers')
    b:close()
end)
