local F = require 'mpv_luatest.framework'
local S = require 'test_asyncio.support'
local asyncio = require 'elxlibs.asyncio'
local std = require 'elxlibs.std'
local locks = require 'elxlibs.asyncio.locks'
local exceptions = require 'elxlibs.asyncio.exceptions'
local await = asyncio.await

F.section('locks / event / semaphore')

F.test('Lock is FIFO and skips cancelled waiters', function()
    S.run(function()
        local lock = locks.Lock()
        F.eq(lock:locked(), false, 'starts unlocked')
        F.contains(tostring(lock), 'unlocked', 'unlocked representation')
        await(lock:acquire())
        F.contains(tostring(lock), 'locked', 'locked representation')
        local order = {}
        local waiters = {}
        for i = 1, 3 do
            waiters[i] = asyncio.create_task(function()
                await(lock:acquire())
                order[#order + 1] = i
                lock:release()
            end)
        end
        await(asyncio.sleep(0))
        waiters[1]:cancel()
        lock:release()
        asyncio.try_await(waiters[1])
        await(waiters[2])
        await(waiters[3])
        F.eq(table.concat(order, ','), '2,3', 'survivors acquire in order')
        F.eq(#lock._waiters, 0, 'waiters removed')
        F.eq(lock:locked(), false, 'all permits returned')
        local ok = pcall(lock.release, lock)
        F.eq(ok, false, 'double release rejected')
    end)
end)

F.test('Event broadcasts, clears, and cleans cancelled waiters', function()
    S.run(function()
        local event = locks.Event()
        F.eq(event:is_set(), false, 'starts clear')
        local a = asyncio.create_task(event:wait())
        local b = asyncio.create_task(event:wait())
        local cancelled = asyncio.create_task(event:wait())
        await(asyncio.sleep(0))
        cancelled:cancel()
        asyncio.try_await(cancelled)
        event:set()
        event:set()
        F.eq(await(a), true, 'first waiter woken')
        F.eq(await(b), true, 'second waiter woken')
        F.eq(await(event:wait()), true, 'set event returns immediately')
        F.eq(#event._waiters, 0, 'all waiters cleaned')
        event:clear()
        local next_wait = asyncio.create_task(event:wait())
        await(asyncio.sleep(0))
        F.eq(next_wait:done(), false, 'clear blocks future waits')
        event:set()
        await(next_wait)
    end)
end)

F.test('blocking primitives reject a different running loop', function()
    local event = locks.Event()
    S.run(function()
        local task = asyncio.create_task(event:wait())
        await(asyncio.sleep(0))
        task:cancel()
        asyncio.try_await(task)
    end)
    S.run(function()
        local ok, err = asyncio.try_await(event:wait())
        F.eq(ok, false, 'cross-loop wait fails')
        F.ok(std.isinstance(err, std.RuntimeError), 'typed loop error')
    end)
end)

F.test('Semaphore capacity is available immediately and release restores it', function()
    local ok, err = pcall(locks.Semaphore, -1)
    F.eq(ok, false, 'negative capacity rejected')
    F.ok(std.isinstance(err, std.ValueError), 'typed constructor error')
    S.run(function()
        local sem = locks.Semaphore(2)
        F.eq(sem:locked(), false, 'positive capacity starts available')
        F.eq(await(sem:acquire()), true, 'first permit')
        F.eq(await(sem:acquire()), true, 'second permit')
        F.eq(sem:locked(), true, 'capacity exhausted')
        sem:release()
        F.eq(sem:locked(), false, 'release makes capacity available')
        F.eq(await(sem:acquire()), true, 'released permit reused')
        local default = locks.Semaphore()
        F.eq(await(default:acquire()), true, 'default capacity is one')
        F.eq(default:locked(), true, 'default exhausted')
    end)
end)

F.test('Semaphore preserves FIFO and cleans successful/cancelled waiters', function()
    S.run(function()
        local sem = locks.Semaphore(0)
        local order, tasks = {}, {}
        for i = 1, 3 do
            tasks[i] = asyncio.create_task(function()
                await(sem:acquire())
                order[#order + 1] = i
                sem:release()
            end)
        end
        await(asyncio.sleep(0))
        tasks[1]:cancel()
        asyncio.try_await(tasks[1])
        sem:release()
        local late = asyncio.create_task(function()
            await(sem:acquire())
            order[#order + 1] = 4
            sem:release()
        end)
        await(tasks[2])
        await(tasks[3])
        await(late)
        F.eq(table.concat(order, ','), '2,3,4', 'new arrivals cannot overtake')
        F.eq(#sem._waiters, 0, 'no historical futures retained')
        F.eq(sem:locked(), false, 'cancelled waiter does not poison locked')
        F.eq(await(sem:acquire()), true, 'permit available after cancellation')
    end)
end)

F.test('Semaphore returns a permit cancelled after wakeup', function()
    S.run(function()
        local sem = locks.Semaphore(0)
        local a = asyncio.create_task(sem:acquire())
        local b = asyncio.create_task(sem:acquire())
        await(asyncio.sleep(0))
        sem:release()
        a:cancel()
        local ok, err = asyncio.try_await(a)
        F.eq(ok, false, 'awakened task cancelled')
        F.ok(std.isinstance(err, exceptions.CancelledError), 'cancellation identity')
        F.eq(await(b), true, 'returned permit wakes next waiter')
        F.eq(#sem._waiters, 0, 'race leaves no waiters')
    end)
end)

F.test('Semaphore.with starts bodies after acquire and enforces capacity', function()
    S.run(function()
        local sem = locks.Semaphore(0)
        local active, peak, ran = 0, 0, 0
        local tasks = {}
        for i = 1, 4 do
            tasks[i] = asyncio.create_task(sem:with(function()
                active = active + 1
                peak = math.max(peak, active)
                ran = ran + 1
                await(asyncio.sleep(0))
                active = active - 1
                return i, nil
            end))
        end
        await(asyncio.sleep(0))
        F.eq(ran, 0, 'zero capacity prevents side effects')
        sem:release()
        for i, task in ipairs(tasks) do
            local result = table.pack(await(task))
            F.eq(result[1], i, 'body result')
            F.eq(result.n, 2, 'trailing nil kept')
        end
        F.eq(peak, 1, 'only one body runs at once')
        F.eq(active, 0, 'all bodies completed')
        F.eq(sem:locked(), false, 'permit returned')
    end)
end)

F.test('Semaphore.with cancellation before acquire never starts the body', function()
    S.run(function()
        local sem = locks.Semaphore(0)
        local ran = false
        local task = asyncio.create_task(sem:with(function() ran = true end))
        await(asyncio.sleep(0))
        task:cancel()
        asyncio.try_await(task)
        sem:release()
        await(asyncio.sleep(0))
        F.eq(ran, false, 'cancelled body has no side effects')
        F.eq(await(sem:acquire()), true, 'no permit leaked or added')
    end)
end)

F.test('Semaphore.with cancellation after acquire but before body restores capacity', function()
    S.run(function()
        local sem = locks.Semaphore()
        local ran = false
        local task = asyncio.create_task(sem:with(function() ran = true end))
        await(asyncio.sleep(0))
        task:cancel()
        F.eq(asyncio.try_await(task), false, 'cancelled wrapper reports failure')
        F.eq(ran, false, 'body never resumed after cancellation')
        F.eq(sem:locked(), false, 'acquired capacity restored')
    end)
end)

F.test('Semaphore.with releases on body failure and running cancellation', function()
    S.run(function()
        local sem = locks.Semaphore()
        local boom = std.RuntimeError('body failed')
        local ok, err = asyncio.try_await(sem:with(function() error(boom) end))
        F.eq(ok, false, 'failure forwarded')
        F.eq(err, boom, 'exception identity kept')
        F.eq(sem:locked(), false, 'failed body releases permit')
        local gate = asyncio.loops.get_running_loop():create_future()
        local started, finished = false, false
        local task = asyncio.create_task(sem:with(function()
            started = true
            await(gate)
            finished = true
        end))
        while not started do await(asyncio.sleep(0)) end
        task:cancel()
        asyncio.try_await(task)
        F.eq(gate:cancelled(), true, 'cancellation reaches body await point')
        F.eq(finished, false, 'body stops')
        F.eq(sem:locked(), false, 'cancelled body releases permit')
        local invalid_ok, invalid_err = asyncio.try_await(sem:with(S.invalid(42)))
        F.eq(invalid_ok, false, 'invalid body rejected')
        F.ok(std.isinstance(invalid_err, std.ValueError), 'typed invalid body error')
        F.eq(sem:locked(), false, 'invalid body does not acquire')
    end)
end)
