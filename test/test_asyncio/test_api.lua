F.test('aggregate exports have direct module identity', function()
    for _, name in ipairs({'tasks', 'loops', 'events', 'futures'}) do
        F.eq(asyncio[name], require('elxlibs.asyncio.' .. name), name .. ' identity')
    end
    for _, name in ipairs({'async', 'await', 'try_await', 'current_task',
        'create_task', 'sleep', 'wait', 'wait_for', 'gather', 'shield'}) do
        F.eq(asyncio[name], asyncio.tasks[name], name .. ' identity')
    end
    F.eq(exceptions.TimeoutError, std.TimeoutError, 'shared TimeoutError')
    F.eq(require('elxlibs.asyncio.futures').PENDING, 'pending', 'pending state constant')
    F.eq(require('elxlibs.asyncio.futures').CANCELLED, 'cancelled', 'cancelled state constant')
    F.eq(require('elxlibs.asyncio.futures').FINISHED, 'finished', 'finished state constant')
end)

F.test('Future state, callbacks, results, exceptions, cancellation', function()
    S.run(function()
        local loop = asyncio.loops.get_running_loop()
        local future = loop:create_future()
        F.eq(future:done(), false, 'pending')
        F.eq(future:cancelled(), false, 'not cancelled')
        local ok, err = pcall(future.result, future)
        F.eq(ok, false, 'pending result unavailable')
        F.ok(std.isinstance(err, exceptions.InvalidStateError), 'typed pending error')
        F.eq(pcall(future.exception, future), false, 'pending exception unavailable')
        local called = 0
        local callback = function(fut)
            F.eq(fut, future, 'callback argument is future')
            called = called + 1
        end
        future:add_done_callback(callback)
        future:add_done_callback(callback)
        future:remove_done_callback(callback)
        future:add_done_callback(callback)
        future:set_result('a', nil, 'c', nil)
        F.eq(called, 0, 'callbacks scheduled asynchronously')
        ---@type {n:integer, [integer]:any}
        local result = table.pack(await(future))
        F.eq(result.n, 4, 'all return slots kept')
        F.eq(result[3], 'c', 'interior nil kept')
        F.eq(future:exception(), nil, 'success has no exception')
        F.eq(future:cancel(), false, 'completed future cannot cancel')
        F.eq(pcall(future.set_result, future, 1), false, 'double completion rejected')
        F.eq(pcall(future.set_exception, future, 'late'), false, 'late error rejected')
        future:add_done_callback(callback)
        await(asyncio.sleep(0))
        F.eq(called, 2, 'removed duplicates stay removed; completed callback runs')
        local failed = loop:create_future()
        local boom = std.RuntimeError('future-boom')
        failed:set_exception(boom)
        F.eq(failed:exception(), boom, 'exception identity')
        local success, caught = asyncio.try_await(failed)
        F.eq(success, false, 'failed await')
        F.eq(caught, boom, 'try_await keeps identity')
        local cancelled = loop:create_future()
        F.eq(cancelled:cancel('reason'), true, 'first cancellation accepted')
        F.eq(cancelled:cancel(), false, 'second cancellation rejected')
        F.eq(cancelled:cancelled(), true, 'cancelled state')
        local cancel_ok, cancel_err = pcall(cancelled.result, cancelled)
        F.eq(cancel_ok, false, 'cancelled result raises')
        F.ok(std.isinstance(cancel_err, exceptions.CancelledError), 'typed cancel error')
        F.contains(cancel_err, 'reason', 'cancel message')
        F.eq(pcall(cancelled.exception, cancelled), false, 'cancelled exception raises')
    end)
end)

F.test('Coroutine nesting preserves returns and rejects invalid yields', function()
    S.run(function()
        local body = function()
            await(asyncio.sleep(0))
            return 'nested', nil, false, nil
        end
        ---@type {n:integer, [integer]:any}
        local values = table.pack(await(asyncio.async(function()
            return await(asyncio.async(body))
        end)))
        F.eq(values.n, 4, 'nested coroutine arity')
        F.eq(values[3], false, 'false value kept')
        local boom = std.RuntimeError('nested-boom')
        local ok, err = asyncio.try_await(asyncio.async(function() error(boom) end))
        F.eq(ok, false, 'nested failure reported')
        F.eq(err, boom, 'nested exception identity')
        for _, body in ipairs({function() coroutine.yield() end,
            function() coroutine.yield('invalid') end}) do
            local valid, error_value = pcall(function()
                return await(asyncio.async(body))
            end)
            F.eq(valid, false, 'unsupported yield rejected')
            F.ok(std.isinstance(error_value, std.RuntimeError), 'typed yield error')
        end
    end)
    F.eq(pcall(function() coroutines.Coroutine(S.invalid(3)) end), false,
        'invalid coroutine constructor')
    local coro = asyncio.async(function() end)
    F.eq(pcall(coro.__await, coro), false, 'direct coroutine await rejected')
    F.eq(pcall(coro.__try_await, coro), false, 'direct coroutine try_await rejected')
end)

F.test('Task supports functions, threads, Coroutine and names', function()
    S.run(function()
        local loop = asyncio.loops.get_running_loop()
        local current = asyncio.current_task()
        F.ok(current ~= nil, 'current task exists inside run')
        F.eq(asyncio.current_task(loop), current, 'explicit loop current task')
        local task = asyncio.create_task(function() return 'f', nil end, 'named')
        F.eq(tostring(task), 'named', 'initial task name')
        task:set_name('renamed')
        F.eq(tostring(task), 'renamed', 'updated task name')
        task:set_name()
        F.contains(tostring(task), 'Task', 'default name restored')
        F.eq(pcall(task.set_result, task, 'bad'), false, 'external task result forbidden')
        F.eq(pcall(task.set_exception, task, 'bad'), false, 'external task error forbidden')
        local result = table.pack(await(task))
        F.eq(result.n, 2, 'task trailing nil kept')
        F.eq(task:cancel(), false, 'done task cannot cancel')
        F.eq(await(asyncio.create_task(coroutine.create(function() return 'thread' end))),
            'thread', 'raw thread accepted')
        F.eq(await(asyncio.create_task(asyncio.async(function() return 'coro' end))),
            'coro', 'Coroutine accepted')
        F.eq(pcall(asyncio.create_task, S.invalid(42)), false, 'invalid task input rejected')
        local failed = asyncio.create_task(function() error(23) end)
        local ok, err = asyncio.try_await(failed)
        F.eq(ok, false, 'non-string error does not hang task')
        F.contains(err, '23', 'non-string error reported')
        local wrong_loop = asyncio.loops.new_event_loop()
        local foreign = wrong_loop:create_future()
        local valid, loop_err = asyncio.try_await(asyncio.async(function() await(foreign) end))
        F.eq(valid, false, 'foreign future rejected')
        F.ok(std.isinstance(loop_err, std.RuntimeError), 'typed foreign-loop error')
        wrong_loop:close()
        local self_ok, self_err = asyncio.try_await(asyncio.async(function()
            await(asyncio.current_task())
        end))
        F.eq(self_ok, false, 'self await rejected')
        F.ok(std.isinstance(self_err, std.RuntimeError), 'typed self-await error')
    end)
end)

F.test('wait completes on all_done, first_done, first_error, timeout and cancellation', function()
    S.run(function()
        local loop = asyncio.loops.get_running_loop()
        local a, b = loop:create_future(), loop:create_future()
        local waiter = asyncio.create_task(asyncio.wait({a, b}))
        await(asyncio.sleep(0))
        a:set_result('a')
        await(asyncio.sleep(0))
        F.eq(waiter:done(), false, 'default waits for every future')
        b:set_result('b')
        await(waiter)
        local pending = loop:create_future()
        await(asyncio.wait({a, pending}, nil, 'first_done'))
        F.eq(pending:done(), false, 'first_done leaves siblings pending')
        local failure = loop:create_future()
        failure:set_exception(std.RuntimeError('first-error'))
        await(asyncio.wait({pending, failure}, nil, 'first_error'))
        failure:exception()
        F.eq(pending:done(), false, 'first_error leaves siblings pending')
        await(asyncio.wait({pending}, 0.001, 'all_done'))
        F.eq(pending:done(), false, 'timeout does not cancel children')
        local cancelled = asyncio.create_task(asyncio.wait({pending}))
        await(asyncio.sleep(0))
        cancelled:cancel()
        local ok, err = asyncio.try_await(cancelled)
        F.eq(ok, false, 'wait wrapper cancelled')
        F.ok(std.isinstance(err, exceptions.CancelledError), 'typed wait cancellation')
        F.eq(#pending._callbacks, 0, 'wait callbacks removed on every exit')
        F.eq(asyncio.try_await(asyncio.wait({})), false, 'empty input rejected')
        F.eq(asyncio.try_await(asyncio.wait({a}, nil, S.invalid('invalid'))), false, 'invalid mode rejected')
        local child_cancel = loop:create_future()
        child_cancel:cancel()
        local success_wait = asyncio.create_task(asyncio.wait({child_cancel, pending}, nil, 'first_error'))
        await(asyncio.sleep(0))
        F.eq(success_wait:done(), false, 'first_error does not stop for child cancellation')
        pending:set_result()
        await(success_wait)
        await(asyncio.sleep(-1))
    end)
end)

F.test('gather handles empty, failed, cancelled and nil-result children', function()
    S.run(function()
        F.eq(next(await(asyncio.gather({}))), nil, 'empty gather is complete')
        local loop = asyncio.loops.get_running_loop()
        local a, b = loop:create_future(), loop:create_future()
        a:set_result(nil)
        b:set_result('second')
        local result = await(asyncio.gather({a, b}))
        F.eq(result[1], nil, 'nil first slot')
        F.eq(result[2], 'second', 'later results do not shift')
        local boom = std.RuntimeError('gather-boom')
        local failed = loop:create_future()
        failed:set_exception(boom)
        local ok, err = asyncio.try_await(asyncio.gather({failed}))
        F.eq(ok, false, 'child error propagates')
        F.eq(err, boom, 'gather exception identity')
        local records = await(asyncio.gather({a, failed}, true))
        F.eq(assert(records[1]).exception, nil, 'successful record')
        F.eq(assert(records[2]).exception, boom, 'failed record')
        local child = asyncio.create_task(function() await(asyncio.sleep(1)) end)
        local group = asyncio.gather({child})
        F.eq(group:cancel('group-cancel'), true, 'group cancellation accepted')
        local group_ok, group_err = asyncio.try_await(group)
        F.eq(group_ok, false, 'cancelled group fails')
        F.ok(std.isinstance(group_err, exceptions.CancelledError), 'typed group cancellation')
        F.eq(child:cancelled(), true, 'group cancellation reaches child')
        F.eq(group:cancel(), false, 'done group cannot cancel')
        local cancelled_child = loop:create_future()
        cancelled_child:cancel('child-cancel')
        local cancelled_records = await(asyncio.gather({cancelled_child}, true))
        F.ok(std.isinstance(cancelled_records[1], exceptions.CancelledError),
            'return_exceptions preserves cancelled child')
        local suppress = asyncio.create_task(function()
            asyncio.try_await(asyncio.sleep(1))
            return 'ignored-cancel'
        end)
        await(asyncio.sleep(0))
        local suppress_group = asyncio.gather({suppress}, true)
        suppress_group:cancel()
        local suppress_ok, suppress_err = asyncio.try_await(suppress_group)
        F.eq(suppress_ok, false, 'group remains cancelled when child suppresses cancellation')
        F.ok(std.isinstance(suppress_err, exceptions.CancelledError), 'typed suppressed-cancel group error')
        local other = asyncio.loops.new_event_loop()
        F.eq(pcall(asyncio.gather, {a, other:create_future()}), false,
            'mixed-loop gather rejected')
        other:close()
    end)
end)

F.test('shield propagates result/error/cancel but isolates outer cancellation', function()
    S.run(function()
        local loop = asyncio.loops.get_running_loop()
        local done = loop:create_future()
        done:set_result('done')
        F.eq(asyncio.shield(done), done, 'done future returned directly')
        local inner = loop:create_future()
        local outer = asyncio.shield(inner)
        inner:set_result('value', nil)
        F.eq(table.pack(await(outer)).n, 2, 'shield keeps result arity')
        local failed = loop:create_future()
        local failed_outer = asyncio.shield(failed)
        local boom = std.RuntimeError('shield-boom')
        failed:set_exception(boom)
        local ok, err = asyncio.try_await(failed_outer)
        F.eq(ok, false, 'inner failure forwarded')
        F.eq(err, boom, 'shield error identity')
        local cancelled = loop:create_future()
        local cancel_outer = asyncio.shield(cancelled)
        cancelled:cancel()
        F.eq(asyncio.try_await(cancel_outer), false, 'inner cancellation forwarded')
        for _, fail in ipairs({false, true}) do
            local survivor = loop:create_future()
            local shield = asyncio.shield(survivor)
            shield:cancel()
            if fail then survivor:set_exception(boom) else survivor:set_result('late') end
            await(asyncio.sleep(0))
            F.eq(survivor:cancelled(), false, 'outer cancellation leaves inner alive')
            F.eq(shield:cancelled(), true, 'late completion does not overwrite outer')
            if fail then survivor:exception() end
        end
    end)
end)

F.test('with supports all body forms and cleans failed enter without running body', function()
    S.run(function()
        local loop = asyncio.loops.get_running_loop()
        local future = loop:create_future()
        future:set_result('future')
        local task = asyncio.create_task(function() return 'task' end)
        local forms = {
            {function() return 'function' end, 'function'},
            {coroutine.create(function() return 'thread' end), 'thread'},
            {asyncio.async(function() return 'coroutine' end), 'coroutine'},
            {future, 'future'}, {task, 'task'},
        }
        local exits = 0
        for _, form in ipairs(forms) do
            local result = await(utils.with(form[1], function(target)
                F.ok(std.isinstance(target, asyncio.tasks.Task), 'enter receives task')
            end, function(err)
                F.eq(err, nil, 'success exit receives nil')
                exits = exits + 1
            end, 'test.with'))
            F.eq(result, form[2], 'body form result')
        end
        F.eq(exits, 5, 'one exit per entered body')
        local thread = coroutine.create(function()
            coroutine.yield()
            return 'raw-yield'
        end)
        F.eq(await(utils.with(thread, function() end, function() end, 'test.with')),
            'raw-yield', 'raw thread keeps Task yield semantics')
        local ran, exited = false, false
        local boom = std.RuntimeError('enter-boom')
        local ok, err = asyncio.try_await(utils.with(function() ran = true end,
            function() error(boom) end, function() exited = true end, 'test.with'))
        await(asyncio.sleep(0))
        F.eq(ok, false, 'failed enter reported')
        F.eq(err, boom, 'enter error identity')
        F.eq(ran, false, 'body never starts after failed enter')
        F.eq(exited, false, 'exit not called for failed enter')
        local false_ok, false_err = asyncio.try_await(utils.with(function() error(false) end,
            function() end, function() end, 'test.with'))
        F.eq(false_ok, false, 'false error is still a failure')
        F.contains(false_err, 'false', 'false error is reported')
        local held_gate = loop:create_future()
        local started, exited_after_cancel = false, false
        local entering = asyncio.create_task(utils.with(function() started = true end,
            function() await(held_gate) end,
            function() exited_after_cancel = true end, 'test.with'))
        await(asyncio.sleep(0))
        entering:cancel()
        F.eq(asyncio.try_await(entering), false, 'cancellation while enter yields is reported')
        await(asyncio.sleep(0))
        F.eq(started, false, 'cancelled enter never starts scheduled body')
        F.eq(exited_after_cancel, false, 'failed enter has no exit')
    end)
end)
